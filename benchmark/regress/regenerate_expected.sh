#!/usr/bin/env bash
# Regenerate test/parity/upstream/geocode_regress_2025_pagc by running PG's
# geocoder with use_pagc_address_parser=true against TIGER 2025 (loaded into
# the pgparity container). Produces deterministic pipe-delimited output that
# the run_geocode_regress.sh harness can byte-compare us against.
#
# Why: the original vendored expected file was generated against PG's built-in
# `normalize_address` parser, NOT PAGC, and against an older TIGER vintage
# (~2010-era based on the test format). When we use PAGC and TIGER 2025, we
# can't expect bit-for-bit match against the vendored file — we need a fresh
# baseline that holds parser + data fixed and compares parser-output only.
#
# Stable secondary sort: rows within a rating tier are ordered by
# ST_AsText(geomout) so re-runs produce byte-identical output.
#
# Usage:
#   ./regenerate_expected.sh
#
# Prereqs:
#   - pgparity container running with TIGER 2025 loaded for MA + MN
#     (run load_tiger_via_pg.sh first if not loaded)

set -eu -o pipefail
cd "$(dirname "$0")/../.."

REPO_ROOT="$(pwd)"
INPUTS="$REPO_ROOT/test/parity/inputs/geocode_regress.csv"
OUT="$REPO_ROOT/test/parity/upstream/geocode_regress_2025_pagc"
CONTAINER="${CONTAINER:-pgparity}"

[[ -f "$INPUTS" ]] || { echo "ERROR: $INPUTS not found" >&2; exit 2; }
docker exec "$CONTAINER" true 2>/dev/null \
    || { echo "ERROR: container '$CONTAINER' not running" >&2; exit 2; }

# Sanity-check TIGER data is present.
n_edges=$(docker exec -u postgres "$CONTAINER" psql -U postgres -d parity -tAc \
    "SELECT count(*) FROM tiger_data.ma_edges" 2>/dev/null || echo 0)
if (( n_edges < 100000 )); then
    echo "ERROR: tiger_data.ma_edges has only $n_edges rows. Run load_tiger_via_pg.sh first." >&2
    exit 2
fi

echo "Streaming inputs CSV into container, running PG geocoder ..."

# Copy the CSV into the container and load into a temp table per session.
# `\copy ... PROGRAM` would let us avoid the docker cp, but the file is small.
docker cp "$INPUTS" "$CONTAINER:/tmp/parity_inputs.csv"

docker exec -i -u postgres "$CONTAINER" psql -U postgres -d parity \
    -A -F'|' -t -X --quiet > "$OUT" <<'SQL'
-- Match how our harness calls geocode: PAGC-on, max 50 candidates, trim
-- per-test via ROW_NUMBER below. Note PG's geocode signature is geocode(raw,
-- max_results) — same as ours after the fix landed.
SELECT tiger.set_geocode_setting('use_pagc_address_parser', 'true');

DROP TABLE IF EXISTS pg_temp.parity_inputs;
CREATE TEMP TABLE parity_inputs (
    test_id    text,
    raw        text,
    max_n      int,
    is_batched int
);
\copy pg_temp.parity_inputs FROM '/tmp/parity_inputs.csv' WITH (FORMAT csv, HEADER true)

-- Output shape mirrors PG's expected file:
--   simple tests:   <id>|<address>|<point>|<rating>      (4 fields)
--   batched tests:  <id>|<address>|<target>|<point>|<rating>  (5 fields)
-- Rows within the same (test_id, raw) get a stable secondary sort by point
-- WKT so re-runs are byte-identical.
WITH geocoded AS (
    SELECT
        inp.test_id, inp.raw AS target, inp.max_n, inp.is_batched,
        g.addy, g.geomout, g.rating,
        ROW_NUMBER() OVER (
            PARTITION BY inp.test_id, inp.raw
            ORDER BY g.rating, ST_AsText(ST_SnapToGrid(g.geomout, 0.00001))
        ) AS rn
    FROM parity_inputs inp
    CROSS JOIN LATERAL geocode(inp.raw, inp.max_n) g
)
SELECT
    test_id || '|' || pprint_addy(addy)
        || CASE WHEN is_batched = 1 THEN '|' || target ELSE '' END
        || '|POINT(' || round(ST_X(geomout)::numeric, 5)::text || ' '
                     || round(ST_Y(geomout)::numeric, 5)::text || ')|'
        || rating::text
FROM geocoded
WHERE rn <= max_n
ORDER BY test_id, target, rating, ST_AsText(ST_SnapToGrid(geomout, 0.00001));
SQL

# Strip noise: set_geocode_setting returns 'true', and psql leaves blank
# lines around \copy. Keep only lines that start with a test-id prefix.
sed -i.bak -E '/^(T[0-9]+[a-z]?|#[A-Za-z0-9]+[a-z]?)\|/!d' "$OUT" && rm -f "${OUT}.bak"

# Add a provenance header. Use # comments — the harness already filters out
# anything that doesn't match a test-id-pipe pattern.
{
    echo "# Generated by benchmark/regress/regenerate_expected.sh"
    echo "# Source: PG 16 + postgis_tiger_geocoder (local mirror) + address_standardizer (master)"
    echo "# Parser: use_pagc_address_parser = true"
    echo "# TIGER vintage: 2025"
    echo "# States loaded: MA, MN"
    echo "# Ordering: test_id, target, rating, geom WKT (deterministic)"
    echo "# Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    cat "$OUT"
} > "${OUT}.tmp" && mv "${OUT}.tmp" "$OUT"

echo "Wrote $(wc -l < "$OUT" | tr -d ' ') lines to $OUT"
echo "Test ID coverage: $(grep -cE '^[T#]' "$OUT") test result rows across $(awk -F'|' '/^[T#]/ {print $1}' "$OUT" | sort -u | wc -l | tr -d ' ') unique test IDs"
